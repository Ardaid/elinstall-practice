// ============================================================
//  Automatikus feldolgozó — ne módosítsd ezt a részt
//
//  Támogatott formátumok:
//    1) svéd szó/kifejezés → magyar fordítás     (egy sorban)
//    2) svéd kifejezés                            (új sor, majd:)
//         → magyar fordítás                      (behúzott →)
//    3) Folytatósorok: 2+ szóközzel behúzott sorok
//       az előző bejegyzés HU részéhez adódnak.
//    4) === Fejezet neve ===                      (fejezet cím)
//    5) 1. SZEKCIÓ / SECTION                      (szekció cím)
//    6) -------- sorok és üres sorok: figyelmen kívül
// ============================================================
function parseWords(text) {
  var lines   = text.split('\n');
  var words   = [];
  var chapter = '';
  var section = '';
  var pending = null;

  function commit() {
    if (pending && pending.sv && pending.hu) {
      words.push({
        chapter: chapter,
        section: section,
        sv: pending.sv.trim(),
        hu: pending.hu.trim()
      });
    }
    pending = null;
  }

  lines.forEach(function(rawLine) {
    var line = rawLine.trim();

    // Kihagyjuk: üres, csak kötőjeles elválasztó
    if (!line || /^-{3,}$/.test(line)) return;

    // === Fejezet cím ===
    var chMatch = line.match(/^===\s*(.+?)\s*===$/);
    if (chMatch) { commit(); chapter = chMatch[1]; section = ''; return; }

    // Szekció cím: pl. "1. ALAPSZAVAK / GRUNDLÄGGANDE ORD"
    if (/^\d+\.\s+\S/.test(line) && !line.includes('→')) {
      commit(); section = line; return;
    }

    // Sor → jellel kezdődik (behúzott folytatás: "  → fordítás")
    if (/^→/.test(line)) {
      if (pending) pending.hu = (pending.hu ? pending.hu + ' ' : '') + line.replace(/^→\s*/, '');
      return;
    }

    // Behúzott folytatósor (legalább 2 szóköz az eredeti sorban)
    if (/^ {2,}/.test(rawLine) && pending) {
      if (pending.hu) pending.hu += ' ' + line;
      return;
    }

    // Normál bejegyzés: tartalmaz →
    if (line.includes('→')) {
      commit();
      var idx = line.indexOf('→');
      var sv  = line.substring(0, idx).trim();
      var hu  = line.substring(idx + 1).trim();
      if (sv) pending = { sv: sv, hu: hu };
      return;
    }

    // Szó → nélkül: SV rész, a fordítás következő sorban (behúzott →)
    commit();
    pending = { sv: line, hu: '' };
  });

  commit();
  return words;
}

